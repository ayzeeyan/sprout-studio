use crate::source::SourceSpan;

#[derive(Clone, Debug, PartialEq)]
pub struct Token {
    pub kind: TokenKind,
    pub span: SourceSpan,
}

#[derive(Clone, Debug, PartialEq)]
pub enum TokenKind {
    Identifier(String),
    Integer(i64),
    Float(f64),
    String(String),
    Has,
    Action,
    Class,
    End,
    If,
    Else,
    Repeat,
    Times,
    While,
    Return,
    Import,
    Python,
    As,
    True,
    False,
    Nil,
    And,
    Or,
    Not,
    LeftParen,
    RightParen,
    LeftBrace,
    RightBrace,
    Comma,
    Dot,
    Colon,
    ColonEqual,
    Semicolon,
    Plus,
    PlusEqual,
    Minus,
    Star,
    Slash,
    Percent,
    Equal,
    EqualEqual,
    Arrow,
    BangEqual,
    Less,
    LessEqual,
    Greater,
    GreaterEqual,
    Newline,
    Indent,
    Dedent,
    Eof,
}

impl TokenKind {
    pub fn name(&self) -> &'static str {
        match self {
            Self::Identifier(_) => "identifier",
            Self::Integer(_) => "integer",
            Self::Float(_) => "float",
            Self::String(_) => "string",
            Self::Has => "`has`",
            Self::Action => "`action`",
            Self::Class => "`class`",
            Self::End => "`end`",
            Self::If => "`if`",
            Self::Else => "`else`",
            Self::Repeat => "`repeat`",
            Self::Times => "`times`",
            Self::While => "`while`",
            Self::Return => "`return`",
            Self::Import => "`import`",
            Self::Python => "`python`",
            Self::As => "`as`",
            Self::True => "`true`",
            Self::False => "`false`",
            Self::Nil => "`nil`",
            Self::And => "`and`",
            Self::Or => "`or`",
            Self::Not => "`not`",
            Self::LeftParen => "`(`",
            Self::RightParen => "`)`",
            Self::LeftBrace => "`{`",
            Self::RightBrace => "`}`",
            Self::Comma => "`,`",
            Self::Dot => "`.`",
            Self::Colon => "`:`",
            Self::ColonEqual => "`:=`",
            Self::Semicolon => "`;`",
            Self::Plus => "`+`",
            Self::PlusEqual => "`+=`",
            Self::Minus => "`-`",
            Self::Star => "`*`",
            Self::Slash => "`/`",
            Self::Percent => "`%`",
            Self::Equal => "`=`",
            Self::EqualEqual => "`==`",
            Self::Arrow => "`=>`",
            Self::BangEqual => "`!=`",
            Self::Less => "`<`",
            Self::LessEqual => "`<=`",
            Self::Greater => "`>`",
            Self::GreaterEqual => "`>=`",
            Self::Newline => "end of line",
            Self::Indent => "an indented block",
            Self::Dedent => "the end of an indented block",
            Self::Eof => "end of file",
        }
    }
}

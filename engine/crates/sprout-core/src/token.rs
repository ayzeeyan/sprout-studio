use crate::source::SourceSpan;

#[derive(Clone, Debug, PartialEq)]
pub struct Token {
    pub kind: TokenKind,
    pub span: SourceSpan,
}

#[derive(Clone, Debug, PartialEq)]
pub enum TokenKind {
    Identifier(String),
    Integer(i64),
    Float(f64),
    String(String),
    Has,
    Action,
    End,
    If,
    Else,
    Repeat,
    Times,
    While,
    Return,
    True,
    False,
    Nil,
    And,
    Or,
    Not,
    LeftParen,
    RightParen,
    Comma,
    Plus,
    Minus,
    Star,
    Slash,
    Percent,
    Equal,
    EqualEqual,
    BangEqual,
    Less,
    LessEqual,
    Greater,
    GreaterEqual,
    Newline,
    Eof,
}

impl TokenKind {
    pub fn name(&self) -> &'static str {
        match self {
            Self::Identifier(_) => "identifier",
            Self::Integer(_) => "integer",
            Self::Float(_) => "float",
            Self::String(_) => "string",
            Self::Has => "`has`",
            Self::Action => "`action`",
            Self::End => "`end`",
            Self::If => "`if`",
            Self::Else => "`else`",
            Self::Repeat => "`repeat`",
            Self::Times => "`times`",
            Self::While => "`while`",
            Self::Return => "`return`",
            Self::True => "`true`",
            Self::False => "`false`",
            Self::Nil => "`nil`",
            Self::And => "`and`",
            Self::Or => "`or`",
            Self::Not => "`not`",
            Self::LeftParen => "`(`",
            Self::RightParen => "`)`",
            Self::Comma => "`,`",
            Self::Plus => "`+`",
            Self::Minus => "`-`",
            Self::Star => "`*`",
            Self::Slash => "`/`",
            Self::Percent => "`%`",
            Self::Equal => "`=`",
            Self::EqualEqual => "`==`",
            Self::BangEqual => "`!=`",
            Self::Less => "`<`",
            Self::LessEqual => "`<=`",
            Self::Greater => "`>`",
            Self::GreaterEqual => "`>=`",
            Self::Newline => "end of line",
            Self::Eof => "end of file",
        }
    }
}
